# Where is the last factor of 2 in M1's own algebra? (10 Nov 2026). Exact arithmetic with quaternions over the rationals.
# PROTOCOL fixed before running: take only objects M1 itself names --
#   the corner units i, j, k of the quaternions (M1 Prop 5.3), and the drive's element w = (1+i+j+k)/2 (M1 Prop 5.6) --
# and compute their orders, the orders of the automorphisms they induce, and the size of the group they generate.
# Report every number.
from fractions import Fraction as Fr
def mul(p, q):
    a, b, c, d = p; e, f, g, h = q
    return (a*e - b*f - c*g - d*h, a*f + b*e + c*h - d*g, a*g - b*h + c*e + d*f, a*h + b*g - c*f + d*e)
ONE = (Fr(1), Fr(0), Fr(0), Fr(0)); NEG = (Fr(-1), Fr(0), Fr(0), Fr(0))
I = (Fr(0), Fr(1), Fr(0), Fr(0)); J = (Fr(0), Fr(0), Fr(1), Fr(0)); K = (Fr(0), Fr(0), Fr(0), Fr(1))
W = (Fr(1, 2), Fr(1, 2), Fr(1, 2), Fr(1, 2))
def order(x):
    n, y = 1, x
    while y != ONE: y = mul(y, x); n += 1
    return n
def conj(p): return (p[0], -p[1], -p[2], -p[3])
def Ad(u, q): return mul(mul(u, q), conj(u))                    # u is a unit, so u^-1 = conj(u)
def ad_order(u):
    n, f = 1, lambda q: Ad(u, q)
    cur = {x: Ad(u, x) for x in (I, J, K)}
    while any(cur[x] != x for x in (I, J, K)):
        cur = {x: Ad(u, cur[x]) for x in (I, J, K)}; n += 1
    return n
print("orders as elements:   i: %d   j: %d   k: %d   w: %d      (i*i = -1: %s;  w^3 = -1: %s)" %
      (order(I), order(J), order(K), order(W), mul(I, I) == NEG, mul(mul(W, W), W) == NEG))
print("orders as automorphisms q -> u q u^-1:   Ad_i: %d   Ad_j: %d   Ad_k: %d   Ad_w: %d" % (ad_order(I), ad_order(J), ad_order(K), ad_order(W)))
print("Ad_w sends  i -> j: %s,  j -> k: %s,  k -> i: %s" % (Ad(W, I) == J, Ad(W, J) == K, Ad(W, K) == I))
def generate(gens):
    G = {ONE}; frontier = [ONE]
    while frontier:
        new = []
        for x in frontier:
            for g in gens:
                y = mul(x, g)
                if y not in G: G.add(y); new.append(y)
        frontier = new
    return G
Q8 = generate([I, J]); G = generate([I, J, W])
print("group generated by the corner units i, j:           %d elements" % len(Q8))
print("  its automorphisms of the algebra (mod +-1):        %d   (the identity and Ad_i, Ad_j, Ad_k)" % (len(Q8)//2))
print("group generated by the corner units and the drive w: %d elements" % len(G))
print("  its automorphisms of the algebra (mod +-1):        %d" % (len(G)//2))
print("  contains -1: %s ; so each automorphism comes from exactly 2 elements, u and -u" % (NEG in G))
