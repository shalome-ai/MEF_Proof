#!/usr/bin/env python3
"""The sign of the lift: every assignment, listed (11 Nov 2026; Decision Log P57, P58).

PROTOCOL, FIXED BEFORE RUNNING.  Exact arithmetic in Q(sqrt 2).

Step 0 (checks the hypothesis the list rests on).  The 48 unit quaternions of the binary
  octahedral group act on Im H by 24 distinct rotations, each a signed permutation of
  (i, j, k) of determinant +1, and those are all 24 such matrices.  So a unit quaternion
  whose rotation keeps the set of three lines {Ri, Rj, Rk} is one of the 48.

Step 1.  SL(2,Z) is generated by S = ((0,-1),(1,0)) and U = a b, a = ((1,1),(0,1)),
  b = ((1,0),(-1,1)), with S^2 = U^3 = -I, S^4 = 1; M0 = U^-1 S U^-2 S (checked on matrices).
  An ASSIGNMENT is a pair (s, u) of the 48 with s^4 = 1 and s^2 = u^3, such that Ad_s and
  Ad_u permute the three LINES C_i, C_j, C_k as S and U permute the corners P2, P3, P4
  (P2 = (1/2,0) <-> C_i, P3 = (0,1/2) <-> C_j, P4 = (1/2,1/2) <-> C_k).  Signs are free.
  For each assignment record, before any total is looked at:
    d      = u^-1 s u^-2 s, the drive's element, and d^3 (+1: three steps; -1: six);
    fold   = s^2 (+1 or -1);
    |H|    = order of the group of rotations generated by Ad_s, Ad_u
             (condition C, "a symmetry that leaves every corner in place leaves i, j, k
             alone", holds exactly when |H| = 6);
    |G|    = order of the group of quaternions generated by s, u.
  Assignments are then grouped by (d^3, fold, |H|, |G|).

Step 2 (the link; a READING, not in M1).  "Each symmetry g carries the unit at a cycled
  corner P to the unit at gP, up to one overall sign for g":
     Ad_{rho(g)}(sig_P e_P) = eps_g sig'_{gP} e_{gP},  eps_g = +1 or -1 the same at the 3 corners,
  tested on the generators S and U, in two variants, for each of the four sign patterns
  sig on (P2, P3, P4) (none odd; odd at P2; at P3; at P4):
     V1 the pattern is carried along by g (sig'_{gP} = sig_P);
     V2 the pattern is held fixed (sig' = sig).
  For each variant and pattern record which groups of Step 1 survive.

What is NOT settled by this script and is taken from the literature (RECALLED, flagged in the
step audit): that S, U with S^4 = 1, S^2 = U^3 is a presentation of SL(2,Z), so that every
assignment is a homomorphism.
"""
from fractions import Fraction as F
from itertools import product, permutations
from collections import Counter, defaultdict

# --- Q(sqrt2) scalars as (a, b) = a + b*sqrt2
def sa(x, y): return (x[0]+y[0], x[1]+y[1])
def sm(x, y): return (x[0]*y[0] + 2*x[1]*y[1], x[0]*y[1] + x[1]*y[0])
def sn(x): return (-x[0], -x[1])
Z0 = (F(0), F(0)); O1 = (F(1), F(0)); H2 = (F(1, 2), F(0)); R = (F(0), F(1, 2))   # R = 1/sqrt2

def qm(p, q):
    a1, b1, c1, d1 = p; a2, b2, c2, d2 = q
    def S4(*ts):
        r = Z0
        for sg, x, y in ts:
            t = sm(x, y); r = sa(r, t if sg > 0 else sn(t))
        return r
    return (S4((1, a1, a2), (-1, b1, b2), (-1, c1, c2), (-1, d1, d2)),
            S4((1, a1, b2), (1, b1, a2), (1, c1, d2), (-1, d1, c2)),
            S4((1, a1, c2), (-1, b1, d2), (1, c1, a2), (1, d1, b2)),
            S4((1, a1, d2), (1, b1, c2), (-1, c1, b2), (1, d1, a2)))
def qc(p): return (p[0], sn(p[1]), sn(p[2]), sn(p[3]))
def qneg(p): return tuple(sn(x) for x in p)
ONE = (O1, Z0, Z0, Z0); MONE = qneg(ONE)
E = [(Z0, O1, Z0, Z0), (Z0, Z0, O1, Z0), (Z0, Z0, Z0, O1)]      # i, j, k

# --- the 48
G48 = set()
for ax in range(4):
    for sg in (1, -1):
        q = [Z0]*4; q[ax] = O1 if sg > 0 else sn(O1); G48.add(tuple(q))
for sg in product((1, -1), repeat=4):
    G48.add(tuple(H2 if x > 0 else sn(H2) for x in sg))
for a in range(4):
    for b in range(a+1, 4):
        for s1, s2 in product((1, -1), repeat=2):
            q = [Z0]*4; q[a] = R if s1 > 0 else sn(R); q[b] = R if s2 > 0 else sn(R); G48.add(tuple(q))
G48 = sorted(G48)
assert len(G48) == 48
for p in G48:                                   # unit norm, closed under product
    assert qm(p, qc(p)) == ONE
assert all(qm(p, q) in set(G48) for p in G48 for q in G48)

def rot(q):
    """Ad_q on (i,j,k) as a signed permutation: tuple of (target index, sign) for i, j, k."""
    out = []
    for e in E:
        v = qm(qm(q, e), qc(q))
        assert v[0] == Z0
        nz = [(n, v[n+1]) for n in range(3) if v[n+1] != Z0]
        assert len(nz) == 1 and nz[0][1] in (O1, sn(O1))
        out.append((nz[0][0], 1 if nz[0][1] == O1 else -1))
    return tuple(out)
def det(r):
    perm = [t for t, _ in r]
    inv = sum(1 for x in range(3) for y in range(x+1, 3) if perm[x] > perm[y])
    return (-1)**inv * r[0][1]*r[1][1]*r[2][1]
ROT = {q: rot(q) for q in G48}
rots = set(ROT.values())
allsp = {tuple(zip(p, s)) for p in permutations(range(3)) for s in product((1, -1), repeat=3)}
alldet1 = {r for r in allsp if det(r) == 1}
print("Step 0: 48 elements; distinct rotations:", len(rots), "; all of determinant +1:", all(det(r) == 1 for r in rots),
      "; equal to the 24 signed permutations of det +1:", rots == alldet1)

# --- SL(2,Z) side
def mm(A, B): return tuple(tuple(sum(A[i][k]*B[k][j] for k in range(2)) for j in range(2)) for i in range(2))
def minv(A): (p, q), (r, s) = A; return ((s, -q), (-r, p))
S = ((0, -1), (1, 0)); a = ((1, 1), (0, 1)); b = ((1, 0), (-1, 1)); U = mm(a, b); M0 = ((2, 1), (1, 1))
Ui = minv(U); NEG = ((-1, 0), (0, -1))
assert mm(S, S) == NEG and mm(U, mm(U, U)) == NEG and mm(mm(mm(Ui, S), mm(Ui, Ui)), S) == M0
CORN = [(1, 0), (0, 1), (1, 1)]                 # P2, P3, P4  <->  lines i, j, k
def cperm(A):
    return tuple(CORN.index(((A[0][0]*m + A[0][1]*n) % 2, (A[1][0]*m + A[1][1]*n) % 2)) for m, n in CORN)
pS, pU, pM = cperm(S), cperm(U), cperm(M0)
print("        corners (P2,P3,P4) -> under S:", pS, " under U:", pU, " under M0:", pM)

def lineperm(q): return tuple(t for t, _ in ROT[q])
def gen_rot(gens):
    def comp(r1, r2):   # r1 after r2
        return tuple((r1[t][0], sg*r1[t][1]) for t, sg in r2)
    seen = set(gens); frontier = list(gens)
    while frontier:
        x = frontier.pop()
        for g in gens:
            y = comp(g, x)
            if y not in seen: seen.add(y); frontier.append(y)
    return seen
def gen_q(gens):
    seen = set(gens); frontier = list(gens)
    while frontier:
        x = frontier.pop()
        for g in gens:
            y = qm(g, x)
            if y not in seen: seen.add(y); frontier.append(y)
    return seen
def qpow(q, n):
    r = ONE
    for _ in range(n): r = qm(r, q)
    return r

assign = []
for s in G48:
    if qpow(s, 4) != ONE or lineperm(s) != pS: continue
    for u in G48:
        if lineperm(u) != pU or qm(s, s) != qpow(u, 3): continue
        ui = qc(u)
        d = qm(qm(qm(ui, s), qm(ui, ui)), s)
        d3 = qpow(d, 3)
        assert d3 in (ONE, MONE) and lineperm(d) == pM
        rec = dict(s=s, u=u, d=d, d3=(1 if d3 == ONE else -1), fold=(1 if qm(s, s) == ONE else -1),
                   H=len(gen_rot([ROT[s], ROT[u]])), G=len(gen_q([s, u])))
        assign.append(rec)

print("\nStep 1: assignments found:", len(assign))
groups = Counter((r["d3"], r["fold"], r["H"], r["G"]) for r in assign)
print("  d^3   fold   |H|   |G|   count   steps   condition C")
for (d3, fold, H, G), c in sorted(groups.items()):
    print(f"  {d3:+d}    {fold:+d}    {H:3d}   {G:3d}   {c:4d}     {'three' if d3 == 1 else 'six  '}   {'holds' if H == 6 else 'fails'}")
print("  cross-table  (condition C, steps):", dict(Counter(('C holds' if r['H'] == 6 else 'C fails', 'three' if r['d3'] == 1 else 'six') for r in assign)))

# --- Step 2
PATTERNS = {"none odd": (1, 1, 1), "odd at P2": (-1, 1, 1), "odd at P3": (1, -1, 1), "odd at P4": (1, 1, -1)}
def link_ok(q, perm, sig, carried):
    r = ROT[q]
    for eps in (1, -1):
        ok = True
        for P in range(3):
            tgt, sg = r[P]                       # Ad_q e_P = sg * e_tgt ; need tgt == perm[P]
            if tgt != perm[P]: ok = False; break
            want = eps * (sig[P] if carried else sig[perm[P]]) * sig[P]   # Ad(sig_P e_P) = eps sig'_{gP} e_{gP}
            if sg != want: ok = False; break
        if ok: return True
    return False
print("\nStep 2: assignments meeting the link on S and U, by (steps, condition C)")
for variant, carried in (("V1 pattern carried", True), ("V2 pattern fixed", False)):
    for name, sig in PATTERNS.items():
        surv = [r for r in assign if link_ok(r["s"], pS, sig, carried) and link_ok(r["u"], pU, sig, carried)]
        tab = dict(Counter(('three' if r['d3'] == 1 else 'six', 'C holds' if r['H'] == 6 else 'C fails', f"|G|={r['G']}", f"fold={r['fold']:+d}") for r in surv))
        print(f"  {variant:20s} {name:10s}: {len(surv):3d} survive  {tab}")
